import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const [designFolder, publicationPhotos] = process.argv.slice(2);
if (!designFolder || !publicationPhotos) {
  throw new Error("Indiquer le dossier de la fiche validée et le dossier des photos publiables.");
}
const here = path.dirname(fileURLToPath(import.meta.url));
const target = path.join(here, "../src/components/place/le-cha-demo/document.ts");
const read = (file) => readFileSync(path.join(designFolder, file), "utf8").replaceAll("\r\n", "\n");
const illustrated = new Set(["okonomiyaki.webp", "mochi.webp", "bubble-milk-tea.webp", "tteokbokki.webp"]);
const credits = JSON.parse(readFileSync(path.join(publicationPhotos, "credits.json"), "utf8")).images
  .filter(image => illustrated.has(image.file));
if (credits.length !== illustrated.size) throw new Error("Crédits incomplets pour les photos du menu.");
const mime = { ".webp": "image/webp", ".svg": "image/svg+xml", ".woff2": "font/woff2" };
const images = {};
function resolveFile(file) {
  const folder = illustrated.has(file) ? publicationPhotos : path.join(designFolder, "assets");
  const diskPath = path.join(folder, file);
  if (!existsSync(diskPath)) throw new Error("Ressource indisponible : " + file);
  const extension = path.extname(file);
  if (!Object.hasOwn(mime, extension)) throw new Error("Extension inattendue : " + file);
  images[file] = "data:" + mime[extension] + ";base64," + readFileSync(diskPath).toString("base64");
}
let html = read("index.html");
html = html.replace(/<link rel="stylesheet" href="([\w-]+\.css)">/g,
  (_, filename) => "<style>\n" + read(filename) + "\n</style>");
html = html.replace(/<script src="([\w-]+\.js)"><\/script>/g, (_, filename) => {
  let source = read(filename);
  if (filename === "menu-le-cha.js") {
    for (const image of credits) {
      const pattern = new RegExp('("photo_url": "assets/' + image.file.replace(".", "\\.") + '",\\s*"photo_alt": )"[^"]*"');
      if (!pattern.test(source)) throw new Error("Entrée de menu introuvable : " + image.file);
      source = source.replace(pattern, (_, prefix) => prefix + JSON.stringify(image.caption));
    }
  }
  if (filename === "distinctions.js") {
    source = source.replaceAll("'assets/' + place.image", "place.image")
      .replace(/image:'([\w-]+\.webp)'/g, "image:'assets/$1'");
  }
  return "<script>\n" + source.replace(/<\/script/gi, "<\\/script") + "\n</script>";
});
const refs = /assets\/([\w.-]+\.(?:webp|svg|woff2))/g;
for (const match of html.matchAll(refs)) {
  if (!(match[1] in images)) resolveFile(match[1]);
}
const escapeHtml = value => value.replaceAll("&","&amp;").replaceAll("<","&lt;").replaceAll(">","&gt;").replaceAll('"',"&quot;");
const creditList = credits.map(image => "<li>" + escapeHtml(image.caption + " · " + image.credit) + "</li>").join("");
const note = '<details class="preview-information"><summary>À propos de cet aperçu</summary><p>Alexandre a fourni son avis et sa photo. Les autres profils, réactions et la distinction de novembre illustrent le fonctionnement de SPAWT.</p><ul>' + creditList + '</ul></details>';
html = html.replace('</section>\n<section id="menu-complet"',note + '</section>\n<section id="menu-complet"');
if (!html.includes('class="preview-information"')) throw new Error("Le panneau Infos pratiques est introuvable");
html = html.replace("</head>",'<style>.preview-information{margin:16px auto;padding:12px 16px;max-width:72rem;font-size:.84rem}.preview-information summary{cursor:pointer}.preview-information p{line-height:1.5}</style></head>');
const wrapper = [
  "// Generated by scripts/package-place-preview.mjs from the approved SPAWT design.",
  'import documentData from "./document.json";',
  'const media: Record<string, string> = documentData.media;',
  'export const leChaDocument = documentData.template.replace(/assets\\/([\\w.-]+\\.(?:webp|svg|woff2))/g, (_, filename: string) => media[filename]!);',
  "",
].join("\n");
const result = JSON.stringify({ media: images, template: html });
mkdirSync(path.dirname(target), {recursive:true});
writeFileSync(path.join(path.dirname(target), "document.json"), result);
writeFileSync(target, wrapper);
if (process.argv[4]) writeFileSync(process.argv[4], html.replace(refs, (_, filename) => images[filename]));
console.log(Object.keys(images).length + " ressources embarquées, " + Buffer.byteLength(result) + " octets.");

